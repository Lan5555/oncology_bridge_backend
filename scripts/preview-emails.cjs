// Run after `npm run build`. Uses sample data and never contacts Brevo.
const { mkdirSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { EmailService } = require('../dist/email/email.service.js');

const output = resolve(__dirname, '../dist/email-previews');
const settings = {
  EMAIL_ENABLED: 'true',
  BREVO_API_KEY: 'preview-only',
  EMAIL_FROM_ADDRESS: 'no-reply@example.com',
  FRONTEND_ORIGIN: 'https://app.example.com',
};
let currentName = '';
const files = [];
const manager = {
  getRepository: () => ({
    save: (row) => {
      const message = JSON.parse(row.payload);
      writeFileSync(resolve(output, `${currentName}.html`), message.html);
      files.push({ name: currentName, subject: message.subject });
      return Promise.resolve(row);
    },
  }),
};
const service = new EmailService(
  { get: (key) => settings[key] },
  { manager },
  { encrypt: (value) => value },
);

async function main() {
  mkdirSync(output, { recursive: true });
  currentName = 'password-reset';
  await service.queuePasswordReset(
    'preview@example.com',
    'preview-token-not-valid',
    new Date(Date.now() + 900000),
    manager,
  );
  currentName = 'welcome';
  await service.queueAccountCreated('preview@example.com', true, manager);
  currentName = 'registration-pending';
  await service.queueAccountCreated('preview@example.com', false, manager);
  currentName = 'review-decision';
  await service.queueNotification(
    'preview@example.com',
    manager,
    'Registration approved',
    'Your registration was approved. You can now sign in.',
  );
  currentName = 'notification';
  await service.queueNotification('preview@example.com', manager);
  currentName = 'password-changed';
  await service.enqueue(
    {
      to: 'preview@example.com',
      subject: 'Your OncoSourz password was changed',
      text: 'Your password was reset and existing refresh sessions were revoked. If you did not make this change, contact your administrator immediately.',
    },
    manager,
  );
  writeFileSync(
    resolve(output, 'index.html'),
    `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>OncoSourz email previews</title><body style="font-family:Arial,sans-serif;max-width:640px;margin:48px auto;padding:0 24px;color:#142f3a"><h1>OncoSourz email previews</h1><p>Sample emails generated by the application. No emails are sent.</p><ul>${files.map((file) => `<li style="margin:18px 0"><a style="color:#087f75" href="${file.name}.html">${file.subject} (${file.name})</a></li>`).join('')}</ul></body></html>`,
  );
  process.stdout.write(`Email previews: ${resolve(output, 'index.html')}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
